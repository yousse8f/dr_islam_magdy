  /// Fetches quotes from Firestore (collection: motivation_messages), caches locally in SharedPreferences,
  /// seeds initial default quotes if empty, and falls back gracefully when offline.
  static Future<List<String>> fetchQuotes() async {
    // 1. Try fetching from Firestore first
    try {
      final querySnapshot = await _firestore
          .collection('motivation_messages')
          .where('isActive', isEqualTo: true)
          .orderBy('order')
          .get()
          .timeout(const Duration(seconds: 4));

      if (querySnapshot.docs.isNotEmpty) {
        final quotes = <String>[];
        for (var doc in querySnapshot.docs) {
          final data = doc.data();
          final msg = data['message']?.toString();
          if (msg != null && msg.trim().isNotEmpty) {
            quotes.add(msg.trim());
          }
        }

        if (quotes.isNotEmpty) {
          await _saveToLocalCache(quotes);
          debugPrint('Successfully loaded ${quotes.length} motivation quotes from Firestore.');
          return quotes;
        }
      } else {
        // If collection is empty in Firestore, seed the 500 default quotes automatically!
        debugPrint('Firestore motivation_messages collection is empty. Seeding 500 quotes...');
        await seedDefaultQuotesToFirestore();
      }
    } catch (e) {
      debugPrint('Error fetching motivation quotes from Firestore (falling back): $e');
    }

    // 2. Try loading from local SharedPreferences cache
    final cached = await _loadFromLocalCache();
    if (cached != null && cached.isNotEmpty) {
      debugPrint('Loaded ${cached.length} motivation quotes from local SharedPreferences cache.');
      return cached;
    }

    // 3. Final fallback to built-in default quotes
    return defaultQuotes;
  }

  /// Automatically seeds all 500 quotes to Firestore collection 'motivation_messages' in batches
  static Future<void> seedDefaultQuotesToFirestore() async {
    try {
      final collectionRef = _firestore.collection('motivation_messages');
      final existing = await collectionRef.limit(1).get();
      if (existing.docs.isNotEmpty) {
        return; // Already seeded
      }

      WriteBatch batch = _firestore.batch();
      int count = 0;

      for (int i = 0; i < defaultQuotes.length; i++) {
        final docRef = collectionRef.doc('mot_${(i + 1).toString().padLeft(3, '0')}');
        batch.set(docRef, {
          'id': 'mot_${(i + 1).toString().padLeft(3, '0')}',
          'message': defaultQuotes[i],
          'isActive': true,
          'order': i + 1,
          'createdAt': FieldValue.serverTimestamp(),
          'updatedAt': FieldValue.serverTimestamp(),
        });

        count++;
        // Firestore batch limit is 500 operations
        if (count >= 400 || i == defaultQuotes.length - 1) {
          await batch.commit();
          batch = _firestore.batch();
          count = 0;
        }
      }
      debugPrint('Successfully seeded ${defaultQuotes.length} motivation quotes to Firestore.');
    } catch (e) {
      debugPrint('Error seeding default quotes to Firestore: $e');
    }
  }

  /// Saves quotes list to SharedPreferences for offline usage
  static Future<void> _saveToLocalCache(List<String> quotes) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_cacheKey, jsonEncode(quotes));
    } catch (e) {
      debugPrint('Error saving motivation quotes to local cache: $e');
    }
  }

  /// Loads quotes list from SharedPreferences
  static Future<List<String>?> _loadFromLocalCache() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final str = prefs.getString(_cacheKey);
      if (str != null) {
        final decoded = jsonDecode(str);
        if (decoded is List) {
          return decoded.map((e) => e.toString()).toList();
        }
      }
    } catch (e) {
      debugPrint('Error loading motivation quotes from local cache: $e');
    }
    return null;
  }

  /// Gets a non-repeating random motivation quote from the active list
  static Future<String> getRandomQuote() async {
    final quotes = await fetchQuotes();
    if (quotes.isEmpty) {
      return "استمر في تحقيق هدفك! خطوة صغيرة يومياً تصنع فرقاً كبيراً 💪";
    }

    final prefs = await SharedPreferences.getInstance();
    final lastQuote = prefs.getString(_lastUsedIdKey);

    List<String> available = quotes;
    if (lastQuote != null && quotes.length > 1) {
      available = quotes.where((q) => q != lastQuote).toList();
    }

    available.shuffle();
    final selected = available.first;
    await prefs.setString(_lastUsedIdKey, selected);
    return selected;
  }
