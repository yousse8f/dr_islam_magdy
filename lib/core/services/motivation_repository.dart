  static Future<String> getQuoteForDate(DateTime date) async {
    final prefs = await SharedPreferences.getInstance();
    final dateStr = '${date.year}-${date.month}-${date.day}';

    final allSaved = prefs.getString(_quoteHistoryKey);
    if (allSaved != null) {
      try {
        final Map<String, dynamic> history = jsonDecode(allSaved);
        if (history.containsKey(dateStr)) {
          return history[dateStr].toString();
        }
      } catch (_) {}
    }

    int currentIndex = prefs.getInt(_currentIndexKey) ?? 0;
    if (currentIndex >= defaultQuotes.length) {
      currentIndex = 0;
    }

    final quote = defaultQuotes[currentIndex];
    currentIndex++;
    await prefs.setInt(_currentIndexKey, currentIndex);

    Map<String, dynamic> history = {};
    if (allSaved != null) {
      try {
        history = jsonDecode(allSaved) as Map<String, dynamic>;
      } catch (_) {}
    }
    history[dateStr] = quote;
    if (history.length > 90) {
      final sortedKeys = history.keys.toList()..sort();
      for (int i = 0; i < history.length - 90; i++) {
        history.remove(sortedKeys[i]);
      }
    }
    await prefs.setString(_quoteHistoryKey, jsonEncode(history));
    return quote;
  }

  static Future<String> getRandomQuote() async {
    return getQuoteForDate(DateTime.now());
  }
